"""Assembler (deterministic): final IDs, requirements.md / .json and run_log.json."""
import json
import re
from datetime import datetime
from pathlib import Path

from .. import config
from .common import current_reqs, event

LABEL = {"conflict": "Conflict", "nonsensical": "Nonsensical", "out_of_scope": "Out of scope",
         "ungrounded": "Ungrounded", "other": "Other"}


def _build(state) -> dict:
    reqs = current_reqs(state)
    areas = list(dict.fromkeys(state.get("areas", []) + [r.area for r in reqs]))
    reqs.sort(key=lambda r: (areas.index(r.area), r.ref))
    rid = {r.ref: f"REQ-{i:03d}" for i, r in enumerate(reqs, 1)}

    def sub(text: str) -> str:
        return re.sub(r"\bR\d{3}\b", lambda m: rid.get(m.group(0), m.group(0)), text)

    rounds = state.get("rounds", [])
    return {
        "generated": datetime.now().isoformat(timespec="seconds"),
        "models": dict(config.MODELS),
        "documents": [{"id": d.doc_id, "file": d.path} for d in state.get("documents", [])],
        "priority_scale": config.PRIORITY_SCALE,
        "scope_summary": state.get("scope_summary", ""),
        "glossary": [g.model_dump() for g in state.get("glossary", [])],
        "requirements": [{"id": rid[r.ref], "name": r.name, "description": r.description,
                          "priority": r.priority, "priority_rationale": r.priority_rationale,
                          "type": r.type, "area": r.area, "sources": r.doc_ids,
                          "candidates": r.merged_from} for r in reqs],
        "discarded": [{"id": f"DIS-{i:03d}", "original_statement": d.statement,
                       "sources": d.doc_ids, "reason_category": d.category,
                       "explanation": sub(d.explanation),
                       "conflicts_with": rid.get(d.conflicts_with or ""), "candidates": d.candidate_ids}
                      for i, d in enumerate(state.get("discarded", []), 1)],
        "validation": {
            "candidates": len(state.get("candidates", {})),
            "rework_loops": state.get("loops", 0),
            "max_iterations": state.get("max_iterations", config.MAX_ITERATIONS),
            "rounds": [{"round": r["round"], "issues": len(r["issues"]),
                        "minor_notes": len(r["minor_notes"])} for r in rounds],
            "unresolved": [sub(i.text) for i in state.get("unresolved", [])],
            "minor_notes": [sub(n) for n in (rounds[-1]["minor_notes"] if rounds else [])],
        },
    }


def _md(doc: dict) -> str:
    v = doc["validation"]
    out = ["# Software Requirements Specification", "",
           f"*Generated by the requirements-refinement network on {doc['generated']}; "
           f"{len(doc['requirements'])} requirements, {len(doc['discarded'])} discarded, "
           f"{v['rework_loops']} rework loop(s).*", "",
           "Models: " + ", ".join(f"{n} = `{m}`" for n, m in doc["models"].items()), "",
           "## 1. Input documents", "", "| ID | File |", "|---|---|",
           *[f"| {d['id']} | `{d['file']}` |" for d in doc["documents"]],
           "", "## 2. Product scope", "", doc["scope_summary"], "",
           "## 3. Priority scale (MoSCoW)", "", "| Priority | Meaning |", "|---|---|",
           *[f"| **{k}** | {t} |" for k, t in doc["priority_scale"].items()],
           "", "## 4. Glossary", "", "| Term | Definition | Avoided synonyms |", "|---|---|---|",
           *[f"| **{g['term']}** | {g['definition']} | {', '.join(g['synonyms']) or '-'} |"
             for g in doc["glossary"]],
           "", "## 5. Requirements", ""]
    area = None
    for r in doc["requirements"]:
        if r["area"] != area:
            area = r["area"]
            out += [f"### {area}", ""]
        out += [f"#### {r['id']}: {r['name']}", "",
                f"**Priority:** {r['priority']} ({r['priority_rationale']})  ",
                f"**Type:** {r['type'].replace('_', '-')} · **Sources:** {', '.join(r['sources'])}"
                f" · **Candidates:** {', '.join(r['candidates'])}", "", r["description"], ""]
    out += ["## 6. Discarded requirements (blacklist)", ""]
    for d in doc["discarded"]:
        out += [f"#### {d['id']}: {LABEL[d['reason_category']]}", "",
                f"- **Original statement:** {d['original_statement']}",
                f"- **Sources:** {', '.join(d['sources'])}"]
        if d["conflicts_with"]:
            out.append(f"- **Conflicts with:** {d['conflicts_with']}")
        out += [f"- **Reason:** {d['explanation']}", ""]
    if not doc["discarded"]:
        out += ["_None._", ""]
    out += ["## 7. Validation summary", "",
            f"- Candidates extracted: {v['candidates']}; rework loops: {v['rework_loops']} "
            f"(cap {v['max_iterations']}).",
            *[f"- Round {r['round']}: {r['issues']} issue(s), {r['minor_notes']} minor note(s)."
              for r in v["rounds"]], ""]
    if v["unresolved"]:
        out += ["**Unresolved warnings (iteration cap reached):**", "",
                *[f"- {u}" for u in v["unresolved"]], ""]
    else:
        out += ["No unresolved issues.", ""]
    if v["minor_notes"]:
        out += ["**Minor reviewer notes (not acted upon):**", "", *[f"- {n}" for n in v["minor_notes"]], ""]
    return "\n".join(out)


def assembler_node(state) -> dict:
    out_dir = Path(state["output_dir"])
    out_dir.mkdir(parents=True, exist_ok=True)
    doc = _build(state)
    (out_dir / "requirements.md").write_text(_md(doc), encoding="utf-8")
    (out_dir / "requirements.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False),
                                               encoding="utf-8")
    log = state.get("log", [])
    calls = [e for e in log if e.get("type") == "llm_call"]
    usage: dict[str, dict] = {}
    for c in calls:
        u = usage.setdefault(c["node"], {"model": c["model"], "calls": 0, "failed": 0,
                                         "input_tokens": 0, "output_tokens": 0})
        u["calls"] += 1
        u["failed"] += 0 if c.get("ok") else 1
        u["input_tokens"] += c["input_tokens"]
        u["output_tokens"] += c["output_tokens"]
    run_log = {"input_dir": state["input_dir"], "generated": doc["generated"],
               "models": doc["models"], "usage_per_node": usage,
               "rework_loops": state.get("loops", 0), "rounds": state.get("rounds", []),
               "nodes_executed": [e for e in log if e.get("type") == "node"], "llm_calls": calls}
    (out_dir / "run_log.json").write_text(json.dumps(run_log, indent=2, ensure_ascii=False),
                                          encoding="utf-8")
    return {"log": [event("assembler")]}
